import fs from 'node:fs/promises';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';
process.on('uncaughtException',e=>{console.error(e.message);process.exit(1);});
const second=process.argv.includes('--corrected');
const w=await SpreadsheetFile.importXlsx(await FileBlob.load(`./artifacts/smoke-ui/SN318_提测前冒烟与UI规范_${second?'二次复核修正':'用例复核'}.xlsx`));
const b=w.worksheets.getItem('本批提测'),u=w.worksheets.getItem('UI检查'),s=w.worksheets.getItem('冒烟用例');
const set=(sh,a,v)=>sh.getRange(a).values=[[v]];
const get=(sh,a)=>sh.getRange(a).values[0][0];
for(let r=6;r<=45;r++)set(u,`D${r}`,'否');
for(let r=6;r<=93;r++)set(s,`D${r}`,'否');
set(b,'B8','AUDIT-BUILD');
set(b,'F57','已确认');set(b,'G57','独立复核用批准规范证据');
set(u,'D41','是');set(u,'F41','已确认');set(u,'G41','通过');set(u,'H41','AUDIT-BUILD');set(u,'M41','复核模拟截图证据');set(u,'O41','复核模拟执行人');set(u,'U41','复核模拟交付项');set(u,'V41',get(b,'B18'));
const result=[];
result.push({scenario:'No requirement/UI baseline metadata or scope confirmation',effective:get(u,'I41'),rate:get(b,'F29'),overall:get(b,'B4')});
set(b,'B7','复核模拟批次');set(b,'B9','复核模拟交付');set(b,'B10','复核模拟需求');set(b,'B11','复核模拟UI');set(b,'B12','已确认');set(b,'B15','复核模拟账号');set(b,'B16','2026-10-12');set(b,'B17','已核对');set(u,'V41',get(b,'B18'));
set(u,'E41','');set(u,'G41','失败');
result.push({scenario:'Blank critical classification with failed result',effective:get(u,'I41'),criticalFailures:get(b,'F27'),overall:get(b,'B4')});
set(s,'D60','是');set(s,'F60','已确认');
result.push({scenario:'SM55 adopted but DEC08 not confirmed',basis:get(s,'V60'),decision:get(b,'H47')});
await fs.writeFile(`./recipes/sn318-smoke-ui-review/probe-${second?'corrected':'results'}.json`,JSON.stringify(result,null,2));
console.log(JSON.stringify(result));process.exit(0);
